import re
from pathlib import Path


def week_dates(week):
    if not isinstance(week, str) or not re.fullmatch(r'[0-9]{4}-W[0-9]{2}', week):
        raise ValueError('week must use YYYY-Www')
    year, number = week.split('-W')
    monday = dt.date.fromisocalendar(int(year), int(number), 1)
    return monday, monday + dt.timedelta(days=6)


def row_map(item):
    return {r['date']: r['value'] for r in item.get('rows', [])}


def difference(current, previous, kind):
    if current is None or previous is None:
        return None
    if kind == 'pct':
        return None if previous == 0 else (current / previous - 1) * 100
    return current - previous


def period_value(item, start, end, calendar):
    values = row_map(item)
    selected = [(d, v) for d, v in sorted(values.items()) if start <= d <= end]
    if item['aggregation'] in ('sum','mean') and item['frequency'] == 'daily':
        expected = [d for d in calendar if start <= d <= end]
        if not expected or any(values.get(d) is None for d in expected):
            return None
        total=sum(values[d] for d in expected)
        return total/len(expected) if item['aggregation']=='mean' else total
    present = [v for _, v in selected if v is not None]
    if not selected or not present:
        return None
    if item['aggregation'] == 'last':
        return selected[-1][1]
    if any(v is None for _, v in selected):
        return None
    return sum(present) / len(present) if item['aggregation'] == 'mean' else sum(present)


def validate(data):
    monday, sunday = week_dates(data['week'])
    def date(value):
        if not isinstance(value, str) or dt.date.fromisoformat(value).isoformat() != value:
            raise ValueError('Dates must use YYYY-MM-DD')
        return value
    calendar = data['calendar']
    for day in calendar:
        date(day)
    if calendar != sorted(set(calendar)):
        raise ValueError('calendar must be sorted and unique')
    current = [d for d in calendar if monday.isoformat() <= d <= sunday.isoformat()]
    previous = [d for d in calendar if (monday - dt.timedelta(days=7)).isoformat() <= d < monday.isoformat()]
    if not current or data['market_end'] != current[-1]:
        raise ValueError('market_end must be the last calendar session in report week')
    if not previous or data['previous_close'] != previous[-1]:
        raise ValueError('previous_close must be the last calendar session in previous week')
    for item in data['indicators'].values():
        for required in ('name', 'unit', 'frequency', 'change_kind', 'aggregation', 'source', 'rows'):
            if required not in item:
                raise ValueError('Missing indicator field: ' + required)
    for key in ('ust', 'cgb', 'hibor', 'weighted', 'div'):
        if key in data['indicators'] and (data['indicators'][key]['unit'] != '%' or
                                         data['indicators'][key]['change_kind'] != 'pp'):
            raise ValueError(key + ' requires percent level (%) and pp change')
    for item in list(data['indicators'].values()) + data.get('earnings', []):
        seen = set()
        for row in item.get('rows', []):
            day, value = date(row['date']), row['value']
            if day in seen:
                raise ValueError('Duplicate observation date')
            seen.add(day)
            if value is not None and (isinstance(value, bool) or not isinstance(value, (int, float))
                                      or not math.isfinite(value)):
                raise ValueError('Values must be finite numbers or null')
        if 'frequency' in item:
            for key, choices in [('frequency', ('daily', 'weekly', 'monthly')),
                                 ('aggregation', ('last', 'mean', 'sum')),
                                 ('change_kind', ('pct', 'pp', 'absolute'))]:
                if item.get(key) not in choices:
                    raise ValueError('Invalid ' + key)
    for key, text in data.get('summary', {}).items():
        if key not in ('headline', 'market', 'flows', 'rates', 'footnote') or not isinstance(text, str):
            raise ValueError('summary accepts named plain-text strings only')


def derived(data):
    items = data['indicators']
    def make(name, rows, frequency='daily'):
        return dict(name=name, rows=rows, unit='%', frequency=frequency,
                    aggregation='last', change_kind='pp', source='derived')
    if 'south_gross' in items and 'turnover' in items:
        gross, turnover = items['south_gross'], items['turnover']
        if gross['unit'] != turnover['unit']:
            raise ValueError('south_gross and turnover must use identical currency and unit')
        weeks = {}
        for day in data['calendar']:
            iso = dt.date.fromisoformat(day).isocalendar()
            weeks.setdefault((iso.year, iso.week), []).append(day)
        rows = []
        for (year, number), days in sorted(weeks.items()):
            start = dt.date.fromisocalendar(year, number, 1).isoformat()
            end = dt.date.fromisocalendar(year, number, 7).isoformat()
            g = period_value(dict(gross, aggregation='sum'), start, end, data['calendar'])
            t = period_value(dict(turnover, aggregation='sum'), start, end, data['calendar'])
            value = g / (2 * t) * 100 if g is not None and t not in (None, 0) else None
            rows.append({'date': days[-1], 'value': value})
        items['share'] = make('南向成交占比', rows, 'weekly')
    if 'ust' in items and 'cgb' in items:
        us, cn = row_map(items['ust']), row_map(items['cgb'])
        shares = {}
        for day, value in row_map(items.get('share', {})).items():
            iso = dt.date.fromisoformat(day).isocalendar()
            shares[(iso.year, iso.week)] = value
        spread, weighted = [], []
        for day in sorted(set(us) | set(cn)):
            u, c = us.get(day), cn.get(day)
            valid = u is not None and c is not None
            spread.append({'date': day, 'value': c - u if valid else None})
            iso = dt.date.fromisoformat(day).isocalendar()
            share = shares.get((iso.year, iso.week))
            value = (u * (1 - share / 100) + c * share / 100) if valid and share is not None else None
            weighted.append({'date': day, 'value': value})
        items['spread'] = make('中美利差', spread)
        items['weighted'] = make('成交占比加权利率', weighted)


def calculate(data):
    validate(data)
    data = copy.deepcopy(data)
    derived(data)
    monday, sunday = week_dates(data['week'])
    end = data['market_end']
    result = {}
    for key, item in data['indicators'].items():
        if item['frequency'] == 'monthly':
            months = {}
            for day, value in sorted(row_map(item).items()):
                if day <= end:
                    months[day[:7]] = value
            keys = sorted(months)
            current = months[keys[-1]] if keys else None
            previous = None
            if len(keys) > 1:
                y, m = map(int, keys[-1].split('-'))
                preceding = (dt.date(y, m, 1) - dt.timedelta(days=1)).strftime('%Y-%m')
                previous = months.get(preceding)
        else:
            current = period_value(item, monday.isoformat(), end, data['calendar'])
            previous = period_value(item, (monday - dt.timedelta(days=7)).isoformat(),
                                    (monday - dt.timedelta(days=1)).isoformat(), data['calendar'])
        result[key] = dict(item, value=current, previous=previous,
                           change=difference(current, previous, item['change_kind']))
    return dict(data, indicators=result)


def prepare(project, as_of=None):
    now = dt.datetime.now().astimezone()
    day = dt.date.fromisoformat(as_of) if as_of else now.date()
    monday = day - dt.timedelta(days=day.weekday())
    if day.weekday() < 5:
        monday -= dt.timedelta(days=7)
    iso = monday.isocalendar()
    return {'week': f'{iso.year}-W{iso.week:02}', 'mon': monday.isoformat(),
            'sun': (monday + dt.timedelta(days=6)).isoformat(),
            'friday': (monday + dt.timedelta(days=4)).isoformat(),
            'generated_at': now.isoformat(), 'project': str(Path(project).resolve())}


