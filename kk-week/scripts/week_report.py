"""Portable, offline weekly report; standard library only (Python 3.9+).

CLI:
    python week_report.py prepare --project PATH [--as-of YYYY-MM-DD]
    python week_report.py render --data normalized.json --out report.html

JSON contract (no network calls; caller supplies normalized observations):
    week: ISO week string YYYY-Www.
    market_end: last HK session in report week, YYYY-MM-DD.
    previous_close: last HK session in immediately previous ISO week.
    calendar: sorted unique HK session dates, complete for both weeks and all
        charted historical periods. Holidays are omitted; never omit a session
        merely because its observation is missing. At least one session in each
        comparison week is required; an all-holiday week is rejected explicitly.
    indicators: mapping of keys to objects with required name, unit, frequency
        (daily|weekly|monthly), change_kind (pct|pp|absolute), aggregation
        (last|mean|sum), source (provenance retained in input, not displayed),
        rows ([{date: YYYY-MM-DD, value: finite number|null}]); optional status
        is descriptive only and does not override rows. Omitted indicators are
        rendered as empty charts. Keys: hsi, hscei, hstech, turnover, ah, pe,
        div, south, foreign, share, ust, hibor, cgb, dxy, weighted, spread,
        pmi, cpi, ppi, m2, credit; optional south_gross for derived share.
    earnings: [{name, rows:[{date,value}], source?}]; percent levels are plotted
        directly on one zero-inclusive scale, never rebased.
    summary: optional plain-text headline, market, flows, rates, footnote.
        Text is escaped, never interpreted as markup or generated by this tool.

Use yield levels such as 4.2 for 4.2%, not .042. Yield/dividend changes use pp;
price returns use pct = (current/previous-1)*100; absolute preserves the unit.
Daily/weekly comparisons never search beyond the specified adjacent ISO weeks.
Monthly compares the latest available month at market_end to its preceding
calendar month. Null terminal observations remain null. Daily sum requires all
calendar sessions. A complete calendar is a caller obligation, not inferred.

When gross and turnover exist, weekly share = sum(south_gross)/(2*sum(turnover))
*100, overriding supplied share. Currency and magnitude units must match.
When both yield series exist, spread = cgb - ust on identical dates; weighted
= ust*(1-share/100) + cgb*share/100 using that date's ISO-week share. These
computed series override supplied ones. No same-date pair or same-week share
means null. No resampling, carry-forward, imputation, or data fetching occurs.
"""
import datetime as dt
import copy
import math
import argparse
import html
