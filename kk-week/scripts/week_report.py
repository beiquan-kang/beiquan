def esc(value):
    return html.escape(str(value), quote=True)


def chart_series(item, calendar, start, end):
    """Keep missing observations as explicit breaks, not interpolated values."""
    values = row_map(item)
    frequency = item.get('frequency', 'daily')
    days = {d for d in values if start <= d <= end}
    if frequency == 'daily':
        days.update(d for d in calendar if start <= d <= end)
    elif days:
        if frequency == 'weekly':
            cursor = dt.date.fromisoformat(min(days))
            while cursor.isoformat() <= end:
                iso = cursor.isocalendar()
                if not any(dt.date.fromisoformat(d).isocalendar()[:2] == iso[:2] for d in days):
                    days.add(cursor.isoformat())
                cursor += dt.timedelta(days=7)
        else:
            cursor = dt.date.fromisoformat(min(days)).replace(day=1)
            last = dt.date.fromisoformat(end).replace(day=1)
            while cursor <= last:
                month = cursor.strftime('%Y-%m')
                if not any(d.startswith(month) for d in days):
                    days.add(cursor.isoformat())
                cursor = (cursor.replace(day=28) + dt.timedelta(days=4)).replace(day=1)
    return [(d, values.get(d)) for d in sorted(days)]


def svg_chart(series, unit, wide=False, common_zero=False):
    width = 1000 if wide else 600
    top, bottom, left, right = 35, 265, 65, width - 150
    height = 310 + max(0, (len(series) - 1) // 3) * 22
    values = [v for _, rows in series for _, v in rows if v is not None]
    days = sorted({d for _, rows in series for d, _ in rows})
    parts = [f'<svg viewBox="0 0 {width} {height}" role="img" aria-label="趋势图" xmlns="http://www.w3.org/2000/svg">']
    if not values:
        parts.append(f'<text x="{width / 2}" y="150" text-anchor="middle">暂无数据</text></svg>')
        return ''.join(parts)
    low, high = min(values + ([0] if common_zero else [])), max(values + ([0] if common_zero else []))
    padding = (high - low) * .12 or max(abs(high) * .05, 1)
    low, high = low - padding, high + padding
    first, last = dt.date.fromisoformat(days[0]).toordinal(), dt.date.fromisoformat(days[-1]).toordinal()
    def x(day):
        ordinal = dt.date.fromisoformat(day).toordinal()
        return left + (ordinal - first) / max(last - first, 1) * (right - left)
    def y(value):
        return bottom - (value - low) / (high - low) * (bottom - top)
    parts.append(f'<text x="{left}" y="18">{esc(unit)}</text>')
    for i in range(5):
        value = low + (high - low) * i / 4
        yy = y(value)
        parts.append(f'<line x1="{left}" x2="{right}" y1="{yy:.2f}" y2="{yy:.2f}" stroke="#E1E7EB"/>')
        parts.append(f'<text class="num" x="{left - 8}" y="{yy + 4:.2f}" text-anchor="end">{value:,.2f}</text>')
    if common_zero:
        yy = y(0)
        parts.append(f'<line x1="{left}" x2="{right}" y1="{yy:.2f}" y2="{yy:.2f}" stroke="#566B79"/>')
    endpoints = []
    for index, (name, rows) in enumerate(series):
        color = COLORS[index % len(COLORS)]
        commands, pen, endpoint = [], False, None
        for day, value in rows:
            if value is None:
                pen = False
                continue
            xx, yy = x(day), y(value)
            commands.append(f'{"L" if pen else "M"}{xx:.2f},{yy:.2f}')
            parts.append(f'<circle cx="{xx:.2f}" cy="{yy:.2f}" r="2" fill="{color}"/>')
            pen, endpoint = True, (xx, yy, value)
        parts.append(f'<path class="series" stroke="{color}" fill="none" stroke-width="2" d="{" ".join(commands)}"/>')
        if endpoint:
            endpoints.append((endpoint[1], index, endpoint, color))
        lx, ly = left + (index % 3) * ((width - left - 12) / 3), 293 + (index // 3) * 22
        parts.append(f'<rect x="{lx:.2f}" y="{ly - 8}" width="10" height="3" fill="{color}"/>')
        parts.append(f'<text x="{lx + 15:.2f}" y="{ly}">{esc(name)}</text>')
    # End values occupy their own right-side gutter; distribute vertically.
    ordered = sorted(endpoints)
    last_label = top - 19
    labels = []
    for yy, index, (xx, actual_y, value), color in ordered:
        label_y = max(yy, last_label + 19)
        labels.append([label_y, xx, actual_y, value, color])
        last_label = label_y
    if labels and labels[-1][0] > bottom:
        shift = labels[-1][0] - bottom
        for label in labels:
            label[0] -= shift
    for label_y, xx, actual_y, value, color in labels:
        parts.append(f'<line x1="{xx + 4:.2f}" y1="{actual_y:.2f}" x2="{right + 9}" y2="{label_y:.2f}" stroke="{color}" opacity=".4"/>')
        parts.append(f'<text class="num end-label" x="{right + 14}" y="{label_y + 4:.2f}" fill="{color}">{value:,.2f}</text>')
    for fraction in (0,.33,.67,1):
        ordinal=round(first+(last-first)*fraction)
        label=dt.date.fromordinal(ordinal).strftime('%Y-%m-%d')
        parts.append(f'<text class="num" x="{left+(right-left)*fraction:.2f}" y="280" text-anchor="middle">{label}</text>')
    parts.append('</svg>')
    return ''.join(parts)


def render(data):
    computed = calculate(data)
    items = computed['indicators']
    monday, sunday = week_dates(data['week'])
    end, calendar = data['market_end'], data['calendar']
    summary = data.get('summary', {})
    nav, sections = [], []
    for section_id, title, charts in GROUPS:
        nav.append(f'<a href="#{section_id}">{title}</a>')
        cards = []
        for key, chart_title in charts:
            wide = key == 'earnings'
            start = (dt.date.fromisoformat(end)-dt.timedelta(days=370)).isoformat()
            unit, series, changes = '', [], []
            if key in ('year-prices', 'week-prices'):
                start = data['previous_close'] if key == 'week-prices' else start
                unit = '定基100'
                # All indices share a base date; no different-date rebasing.
                keys = [k for k in ('hsi', 'hscei', 'hstech') if k in items]
                maps = [row_map(items[k]) for k in keys]
                common = sorted(d for d in set.intersection(*(set(m) for m in maps))
                                if start <= d <= end and all(m[d] not in (None, 0) for m in maps)) if maps else []
                base_day = common[0] if common else None
                if key == 'week-prices' and base_day != data['previous_close']:
                    base_day = None
                for k in keys:
                    item = items[k]
                    rows = chart_series(item, calendar, start, end)
                    base = row_map(item).get(base_day)
                    rows = [(d, v / base * 100 if base and v is not None and d >= base_day else None)
                            for d, v in rows]
                    series.append((item['name'], rows))
                    changes.append((item['name'], item['change'], item['change_kind'], item['unit']))
            elif wide:
                unit = '%'
                for earning in data.get('earnings', []):
                    eitem=dict(earning,frequency='weekly',aggregation='last',change_kind='pp')
                    series.append((earning['name'], chart_series(eitem, calendar, start, end)))
                    current=period_value(eitem,monday.isoformat(),end,calendar)
                    previous=period_value(eitem,(monday-dt.timedelta(days=7)).isoformat(),(monday-dt.timedelta(days=1)).isoformat(),calendar)
                    changes.append((earning['name'],difference(current,previous,'pp'),'pp','%'))
            else:
                item = items.get(key)
                if item:
                    unit = item['unit']
                    series = [(item['name'], chart_series(item, calendar, start, end))]
                    changes = [(item['name'], item['change'], item['change_kind'], unit)]
            change_html = []
            for name, change, kind, original_unit in changes:
                suffix = '%' if kind == 'pct' else 'pp' if kind == 'pp' else original_unit
                text = '—' if change is None else f'{change:+,.2f}{suffix}'
                change_html.append(f'<span>{esc(name)} <b class="num">{esc(text)}</b></span>')
            valid_dates=[d for _,rs in series for d,v in rs if v is not None]
            actual=max(valid_dates) if valid_dates else None
            stamp=f'截至{actual}' if actual else '暂无有效数据'
            if actual and actual<end:stamp+='；报告日数据缺失' if key not in ('pmi','cpi','ppi','m2','credit','foreign') else ''
            label='较上月变化' if key in ('pmi','cpi','ppi','m2','credit') else '本周变化'
            cards.append(f'<article id="{key}" class="chart{" wide" if wide else ""}"><h3>{chart_title}</h3>'
                         +f'<div class="chart-dates">{stamp}</div>'
                         + svg_chart(series, unit, wide, wide)
                         +f'<div class="change-label">{label}</div><div class="changes">{"".join(change_html)}</div></article>')
        summary_key = {'market': 'market', 'flows': 'flows', 'liquidity': 'rates'}.get(section_id)
        paragraph = f'<p class="summary">{esc(summary[summary_key])}</p>' if summary_key and summary.get(summary_key) else ''
        sections.append(f'<section id="{section_id}"><h2>{title}</h2><div class="grid">{"".join(cards)}</div></section>')
    note = f'<p class="summary">{esc(summary["footnote"])}</p>' if summary.get('footnote') else ''
    intro='<div class="quick-read"><h2>本周速读</h2><p>'+esc(summary.get('headline',''))+'</p>'
    for key,title in [('market','市场'),('flows','资金'),('rates','利率')]:
        if summary.get(key):intro+=f'<p><strong>{title}｜</strong>{esc(summary[key])}</p>'
    intro+=note+'</div>'
    return ('<!doctype html><html lang="zh-CN"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1"><title>港股周报</title><style>'
            + CSS + '</style></head><body><div class="layout"><nav aria-label="栏目">'
            + ''.join(nav) + '</nav><main><header><p class="eyebrow">香港市场 · 周报</p>'
            + f'<h1>港股周报</h1><p class="num">{esc(data["week"])} · {monday} — {sunday}</p></header>'
            + intro+''.join(sections)
            + '<footer>AI辅助生成，仅供参考，不构成投资建议；请独立核验数据及判断。</footer></main></div><script>'
            + SCRIPT + '</script></body></html>')


