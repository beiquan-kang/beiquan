def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    prep = commands.add_parser('prepare', help='Print target week; no network or file writes')
    prep.add_argument('--project', required=True)
    prep.add_argument('--as-of')
    computing=commands.add_parser('compute',help='Print exact computed indicator values')
    computing.add_argument('--data',required=True)
    drawing = commands.add_parser('render', help='Render normalized JSON as self-contained HTML')
    drawing.add_argument('--data', required=True)
    drawing.add_argument('--out', required=True)
    args = parser.parse_args(argv)
    try:
        if args.command == 'prepare':
            print(json.dumps(prepare(args.project, args.as_of), ensure_ascii=True, indent=2))
        elif args.command=='compute':
            data=json.loads(Path(args.data).read_text(encoding='utf-8-sig'))
            print(json.dumps(calculate(data),ensure_ascii=True,allow_nan=False))
        else:
            data = json.loads(Path(args.data).read_text(encoding='utf-8-sig'))
            page = render(data)
            output = Path(args.out)
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(page, encoding='utf-8')
            print(json.dumps({'out': str(output.resolve()), 'charts': 21, 'week': data['week']}, ensure_ascii=True))
    except (ValueError, KeyError, TypeError, OSError) as error:
        parser.exit(2, f'error: {error}\n')


if __name__ == '__main__':
    main()
